#!/usr/bin/env python
"""Operator/local-fixture setup; never invoked by the API process.

Uses the configured database and requires its owner's DDL privileges. Concurrent
index creation is intentionally outside a transaction so normal reads continue.
"""

import argparse

from pathlib import Path

import psycopg

from roadmap.config import Settings
from roadmap.v2.package_tokens import catalog_tokens
from roadmap.v2.package_tokens import expression
from roadmap.v2.package_tokens import index_name
from roadmap.v2.package_tokens import rules_function_sql
from roadmap.v2.package_tokens import rules_json


def statements() -> tuple[str, str, str, str, str]:
    rules = rules_json(catalog_tokens())
    name = index_name(rules)
    function = Path(__file__).with_name("sql").joinpath("v2_inventory_function.sql").read_text()
    function += "\n" + rules_function_sql(rules)
    statistics = (
        "CREATE STATISTICS IF NOT EXISTS hbi.roadmap_exp_os_major_stats\n"
        "    ON (operating_system ->> 'major')\n"
        "    FROM hbi.system_profiles_static;"
    )
    index = (
        f"CREATE INDEX CONCURRENTLY IF NOT EXISTS {name}\n"
        f"ON hbi.system_profiles_dynamic USING gin (({expression(rules, stored_rules=True)}));"
    )
    analyze = "ANALYZE hbi.hosts;\nANALYZE hbi.system_profiles_static;\nANALYZE hbi.system_profiles_dynamic;"
    return function, statistics, index, analyze, name


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--output-sql", type=Path, help="Export catalog-specific owner SQL without connecting or applying"
    )
    args = parser.parse_args()
    function, statistics, index, analyze, name = statements()
    if args.output_sql:
        args.output_sql.write_text(
            "-- Generated by scripts/install_v2_inventory.py --output-sql.\n"
            "-- Apply outside a transaction as the HBI database owner.\n"
            "-- Install before deploying matching catalog/query changes; retain old indexes until verified.\n\n"
            + "\n\n".join((function, statistics, index, analyze))
            + "\n"
        )
        print(f"Exported {name} to {args.output_sql}")
        return
    settings = Settings.create()
    with psycopg.connect(
        host=settings.db_host,
        port=settings.db_port,
        dbname=settings.db_name,
        user=settings.db_user,
        password=settings.db_password.get_secret_value(),
        autocommit=True,
    ) as connection:
        connection.execute(function)
        connection.execute(statistics)
        connection.execute(index)
        connection.execute(analyze)
        valid = connection.execute(
            "SELECT indisvalid FROM pg_index WHERE indexrelid=to_regclass(%s)", (f"hbi.{name}",)
        ).fetchone()
        if not valid or not valid[0]:
            raise RuntimeError("The v2 package index is invalid; drop the invalid index and retry installation")
    print(f"Organization-scoped catalog token index ready: {name}")


if __name__ == "__main__":
    main()
